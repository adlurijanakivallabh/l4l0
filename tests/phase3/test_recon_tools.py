@pytest.mark.parametrize("runner_cls", _ALL_RUNNERS)
def test_command_is_an_array_with_target_as_a_distinct_element(
    runner_cls: type[ReconToolRunner],
) -> None:
    runner = runner_cls(graph=ReachabilityGraph(), scope=_scope())
    argv = runner.command(_TARGET)
    # An argv LIST, not a shell string.
    assert isinstance(argv, list)
    assert all(isinstance(arg, str) for arg in argv)
    # The target is a whole element, never concatenated into another arg.
    assert _TARGET in argv
    # No element smuggles a shell metacharacter around the target.
    assert not any(";" in a or "&&" in a or "|" in a for a in argv)


def test_hostile_target_stays_a_single_arg_element() -> None:
    # A target carrying shell metacharacters must remain ONE argv element — with
    # shell=False that is inert, never a shell break-out.
    hostile = "target.test; rm -rf /"
    argv = NmapRunner(graph=ReachabilityGraph(), scope=_scope()).command(hostile)
    assert hostile in argv  # the whole hostile string is one element
    # It never gets split/joined into a shell string.
    assert argv.count(hostile) == 1


def test_live_spawn_uses_shell_false_and_array(monkeypatch: pytest.MonkeyPatch) -> None:
    # Capture the exact subprocess.run call the live path makes.
    import reachagent.recon.tools.base as base

    captured: dict[str, object] = {}

    class _Completed:
        stdout = ""

    def _fake_run(argv: object, **kwargs: object) -> _Completed:
        captured["argv"] = argv
        captured["kwargs"] = kwargs
        return _Completed()

    monkeypatch.setattr(base.shutil, "which", lambda _b: "/usr/bin/nmap")
    monkeypatch.setattr(base.subprocess, "run", _fake_run)
    runner = NmapRunner(graph=ReachabilityGraph(), scope=_scope())

    runner.run(_TARGET, environ={base.RECON_ENV_LIVE: "1"})

    assert isinstance(captured["argv"], list)  # array, not a string
    assert captured["kwargs"]["shell"] is False  # never shell=True
    assert _TARGET in captured["argv"]  # target is an element


