def test_nmap_emits_host_and_open_services() -> None:
    graph, scope = _graph_and_scope()
    runner = NmapRunner(graph=graph, scope=scope)
    result = runner.ingest(_TARGET, _fixture("nmap-target.xml"))

    assert result.outcome is ReconOutcome.INGESTED
    # One host, keyed by its IPv4 address, tech from osmatch.
    hosts = graph.hosts()
    assert len(hosts) == 1
    host_node, host = hosts[0]
    assert host_node == host_id("93.184.216.34")
    assert host.hostname == "target.test"
    assert host.source == "nmap"
    assert host.technology == "Linux 5.X"
    # Only the three OPEN ports become services — the closed 3306 does not.
    services = graph.services()
    assert len(services) == 3
    ports = {s.port for _, s in services}
    assert ports == {22, 80, 443}
    # runs_service edges connect host → each service.
    assert len(graph.runs_service_edges()) == 3
    # A service carries its version banner (a fact), no status.
    http = next(s for _, s in services if s.port == 80)
    assert http.service_name == "http"
    assert http.detected_version == "1.24.0"
    assert "nginx" in (http.banner or "")


