_ALL_RUNNERS = [NmapRunner, AmassRunner, SubfinderRunner, GobusterRunner, WhatWebRunner]


@pytest.mark.parametrize("runner_cls", _ALL_RUNNERS)
def test_out_of_scope_target_is_refused_and_audited(runner_cls: type[ReconToolRunner]) -> None:
    graph = ReachabilityGraph()
    scope = ScopeGuard.from_hosts(["in-scope.test"])  # target.test is NOT allowed
    runner = runner_cls(graph=graph, scope=scope)

    result = runner.ingest("evil.test", "irrelevant output")

    assert result.outcome is ReconOutcome.REFUSED_OUT_OF_SCOPE
    # Nothing was written to the graph for an out-of-scope target.
    assert graph.node_count() == 0
    # And the refusal is audited, same discipline as the firer.
    assert runner.audit.entries[-1].outcome == ReconOutcome.REFUSED_OUT_OF_SCOPE


def test_live_run_refuses_out_of_scope_before_spawning(monkeypatch: pytest.MonkeyPatch) -> None:
    # Even on the live path, scope is enforced BEFORE any spawn. We make a spawn
    # explode if reached; an out-of-scope target must never reach it.
    import reachagent.recon.tools.base as base

    def _boom(*_a: object, **_k: object) -> object:
        raise AssertionError("subprocess.run must not be reached for an out-of-scope target")

    monkeypatch.setattr(base.subprocess, "run", _boom)
    graph = ReachabilityGraph()
    scope = ScopeGuard.from_hosts(["in-scope.test"])
    runner = NmapRunner(graph=graph, scope=scope)

    result = runner.run("evil.test", environ={base.RECON_ENV_LIVE: "1"})

    assert result.outcome is ReconOutcome.REFUSED_OUT_OF_SCOPE
    assert graph.node_count() == 0


