def test_missing_binary_skips_cleanly(monkeypatch: pytest.MonkeyPatch) -> None:
    import reachagent.recon.tools.base as base

    # Binary absent from PATH.
    monkeypatch.setattr(base.shutil, "which", lambda _b: None)
    # Guard: a spawn must not be attempted when the binary is missing.
    monkeypatch.setattr(
        base.subprocess,
        "run",
        lambda *_a, **_k: (_ for _ in ()).throw(
            AssertionError("must not spawn when binary is missing")
        ),
    )
    graph = ReachabilityGraph()
    runner = NmapRunner(graph=graph, scope=_scope())

    result = runner.run(_TARGET, environ={base.RECON_ENV_LIVE: "1"})

    assert result.outcome is ReconOutcome.SKIPPED_MISSING_BINARY
    assert graph.node_count() == 0
    assert runner.audit.entries[-1].outcome == ReconOutcome.SKIPPED_MISSING_BINARY


